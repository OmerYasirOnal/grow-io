// Adopts the UIScene life cycle on iOS.
//
// Apps linked against the iOS 27 SDK that still use the legacy
// AppDelegate-owned window are stopped at launch by UIKit
// (_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption ->
// EXC_BREAKPOINT). Expo SDK 54's template does not adopt scenes, so this
// plugin, on every prebuild:
//   1. adds UIApplicationSceneManifest to Info.plist (single window scene),
//   2. writes ios/<Project>/SceneDelegate.swift and adds it to the target,
//   3. moves window creation + startReactNative out of
//      application(_:didFinishLaunchingWithOptions:) into the scene delegate.
// The scene delegate also forwards the four foreground/background callbacks to
// the app delegate, so Expo subscribers see the same events as before.
const fs = require('fs');
const path = require('path');
const {
  withInfoPlist,
  withAppDelegate,
  withXcodeProject,
  withDangerousMod,
  IOSConfig,
} = require('@expo/config-plugins');

const SCENE_DELEGATE = `import UIKit
import React

// Generated by plugins/withSceneDelegate.js. Do not edit: changes are lost on prebuild.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene, let app = appDelegate else { return }
    let window = UIWindow(windowScene: windowScene)
    self.window = window
    app.window = window
    app.reactNativeFactory?.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: nil)
    if let url = connectionOptions.urlContexts.first?.url {
      _ = RCTLinkingManager.application(UIApplication.shared, open: url, options: [:])
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let url = URLContexts.first?.url else { return }
    _ = RCTLinkingManager.application(UIApplication.shared, open: url, options: [:])
  }

  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }
}
`;

// The template block that creates the window inside didFinishLaunching.
// Other plugins (e.g. @react-native-firebase/app's FirebaseApp.configure())
// may insert `// @generated` blocks between the window and startReactNative
// lines; those are captured and kept in didFinishLaunching.
const WINDOW_BLOCK = /#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n((?:[ \t]*\/\/ @generated begin[\s\S]*?\/\/ @generated end[^\n]*\n)*)\s*factory\.startReactNative\(\s*\n?\s*withModuleName: "main",\s*\n?\s*in: window,\s*\n?\s*launchOptions: launchOptions\)\s*\n\s*#endif\s*\n/;
const MARKER = '// The window is created by SceneDelegate (plugins/withSceneDelegate.js).';

function withSceneManifest(config) {
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });
}

function withSceneAppDelegate(config) {
  return withAppDelegate(config, (cfg) => {
    if (cfg.modResults.language !== 'swift') {
      throw new Error('withSceneDelegate: expected a Swift AppDelegate');
    }
    let src = cfg.modResults.contents;
    if (!src.includes(MARKER)) {
      if (!WINDOW_BLOCK.test(src)) {
        throw new Error('withSceneDelegate: AppDelegate template changed; update WINDOW_BLOCK');
      }
      src = src.replace(WINDOW_BLOCK, (_m, generated) => `    ${MARKER}\n${generated || ''}`);
    }
    cfg.modResults.contents = src;
    return cfg;
  });
}

function withSceneDelegateFile(config) {
  config = withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const name = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
      const file = path.join(cfg.modRequest.platformProjectRoot, name, 'SceneDelegate.swift');
      fs.writeFileSync(file, SCENE_DELEGATE);
      return cfg;
    },
  ]);
  return withXcodeProject(config, (cfg) => {
    const name = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const filepath = `${name}/SceneDelegate.swift`;
    if (!cfg.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: name,
        project: cfg.modResults,
      });
    }
    return cfg;
  });
}

module.exports = function withSceneDelegate(config) {
  config = withSceneManifest(config);
  config = withSceneAppDelegate(config);
  config = withSceneDelegateFile(config);
  return config;
};
